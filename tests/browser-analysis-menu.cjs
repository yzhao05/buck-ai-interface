  await page.locator('#chat-input').fill('保留在原对话中的草稿');await page.locator('#vin').fill('29');
  await page.route('**/analysis-copy',route=>route.fulfill({status:503,json:{detail:'test copy unavailable'}}));
  await openMenu();await page.locator('#analyze-new').click();await ready();
  assert.equal(await page.evaluate(()=>activeConversation.id),source.id);
  assert.equal(chats.length,1,'A copy failure does not send or leave the source');
  await page.unroute('**/analysis-copy');
  await openMenu();await page.locator('#analyze-new').click();
  await page.waitForFunction(id=>activeConversation.id!==id&&activeConversation.messages.length===2&&!state.chatBusy,source.id);await ready();
  const target=await page.evaluate(()=>({id:activeConversation.id,resultId:state.resultId,parameters:state.result.parameters,truth:parameterComparison()}));
  assert.notEqual(target.resultId,source.resultId);assert.deepEqual(target.parameters,source.parameters);
  assert.deepEqual(target.truth,source.truth);assert.equal(fits,1);
  assert.equal(chats.at(-1).owner,target.id);assert.deepEqual(chats.at(-1).body.history,[]);
  assert.deepEqual(chats.at(-1).body.conversation_messages,[]);assert.equal(chats.at(-1).body.result_id,target.resultId);
  assert.equal(chats.at(-1).body.options.vin,28,'Carry original result settings, not the unsubmitted draft');
  assert.equal(chats.at(-1).body.ground_truth.result_id,target.resultId);
  assert.match(await page.locator('.message.assistant').last().innerText(),/真实电感 60 μH/);
  await page.locator(`[data-conversation-id="${source.id}"]`).click();await ready();
  assert.equal(await page.locator('.message').count(),oldMessages);assert.equal(await page.locator('#chat-input').inputValue(),'保留在原对话中的草稿');
  assert.equal(await page.locator('#vin').inputValue(),'29');assert.equal(await page.evaluate(()=>state.resultId),source.resultId);
  await page.locator(`[data-conversation-id="${target.id}"]`).click();await ready();
  await page.reload();await ready();await page.waitForFunction(()=>state.result);
  assert.equal(await page.evaluate(()=>state.resultId),target.resultId);
  await page.locator('#enter-identification').click();
  await page.locator('#language-toggle').click();await openMenu();
  assert.deepEqual(await page.locator('#analysis-menu button').allTextContents(),['Analyze in this conversation','Analyze in a new conversation']);
