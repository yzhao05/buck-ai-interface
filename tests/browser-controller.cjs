// Local backend at :8001; no model API key is needed.
const {chromium}=require('../.tmp/browser/node_modules/playwright-core');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
 const page=await browser.newPage({viewport:{width:1500,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const ready=()=>page.locator('#send-chat:not([disabled])').waitFor({timeout:60000});
 try {
  await page.goto('http://127.0.0.1:8001');await ready();
  const csv=fs.readFileSync('examples/plecs_buck_case16a.csv','utf8').split(/\r?\n/).filter(Boolean).map(line=>line.split(',').slice(0,3).join(',')).join('\n');
  await page.locator('#csv-file').setInputFiles({name:'three-signals.csv',mimeType:'text/csv',buffer:Buffer.from(csv)});await ready();
  assert.equal(await page.locator('#map-pwm').inputValue(),'');
  await page.locator('#enter-identification').click();
  assert.equal(await page.locator('#pwm-source').inputValue(),'auto');
  assert(await page.locator('#controller-settings').isVisible());
  assert.equal(await page.locator('#fit-mode').inputValue(),'LC');
  assert(await page.locator('#fit-mode option[value=LCR]').evaluate(el=>el.disabled));
  assert.equal(await page.locator('#end-ms').inputValue(),'0.8');
  await page.locator('#fit-method').selectOption('weighted_integral');
  await page.locator('#identify').click();await ready();
  assert((await page.locator('#notice-text').textContent()).includes('请先确认控制电路'));
  await page.locator('#fixed-r').fill('6');await page.locator('#controller-confirmed').selectOption('yes');
  await page.locator('#identify').click();await ready();
  assert(Math.abs(Number(await page.locator('#result-l').textContent())-60)<1);
  assert(Math.abs(Number(await page.locator('#result-c').textContent())-500)<10);
  assert.equal(await page.locator('#result-r').textContent(),'6');
  assert((await page.locator('#r-label').textContent()).includes('固定'));
  assert((await page.locator('#result-notes').textContent()).includes('自主闭环'));
  assert((await page.locator('#result-notes').textContent()).includes('PWM 重建已完成'));
  await page.reload();await ready();
  assert.equal(await page.locator('#pwm-source').inputValue(),'auto');
  assert.equal(await page.locator('#controller-confirmed').inputValue(),'yes');
  assert.equal(await page.locator('#fit-mode').inputValue(),'LC');
  await page.locator('#enter-identification').click();
  const statistics=await page.locator('#stat-voltage').textContent();
  await page.locator('#language-toggle').click();
  assert.equal(await page.locator('#stat-voltage').textContent(),statistics,'Language changes preserve waveform statistics');
  assert.equal(await page.locator('#wave-subtitle').textContent(),'three-signals.csv');
  assert(!/[\u3400-\u9fff]/.test(await page.locator('#controller-settings').innerText()));
  assert((await page.locator('#result-notes').textContent()).includes('autonomous'));
  assert((await page.locator('#result-notes').textContent()).includes('PWM reconstruction completed'));
  const englishDiagnostics=await page.locator('#diagnostic-text').textContent();
  assert(!/[\u3400-\u9fff]/.test(englishDiagnostics),'Reconstruction diagnostics and warnings must be English');
  assert((await page.locator('#map-pwm').locator('..').textContent()).includes('(optional)'));
  assert(!(await page.locator('#pwm-source').textContent()).match(/[\u3400-\u9fff]/));
  const originalWarnings=await page.evaluate(()=>JSON.stringify(state.result.warnings));
  await page.locator('#language-toggle').click();
  assert((await page.locator('#diagnostic-text').textContent()).includes('训练段电压重建'));
  await page.locator('#language-toggle').click();
  assert.equal(await page.locator('#diagnostic-text').textContent(),englishDiagnostics);
  assert.equal(await page.evaluate(()=>JSON.stringify(state.result.warnings)),originalWarnings,'Translation must not mutate report data');
  await page.screenshot({path:'runtime/controller-interface-english.png',fullPage:true});
  for(const width of [900,390,320]){
   await page.setViewportSize({width,height:900});
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  }
  await page.setViewportSize({width:1500,height:1000});
  const previousL=await page.locator('#result-l').textContent();
  await page.locator('#pwm-source').selectOption('measured');
  assert(!(await page.locator('#fit-mode option[value=LCR]').evaluate(el=>el.disabled)));
  assert(await page.locator('#controller-settings').isHidden());
  assert.equal(await page.locator('#result-l').textContent(),previousL,'Changing draft drive source preserves previous results');
  await page.locator('#pwm-source').selectOption('auto');
  await page.locator('#csv-file').setInputFiles('examples/plecs_buck_case16a.csv');await ready();
  assert.notEqual(await page.locator('#map-pwm').inputValue(),'');
  assert(await page.locator('#controller-settings').isHidden(),'Mapped PWM bypasses reconstruction');
  assert.equal(await page.locator('#controller-confirmed').inputValue(),'no','New uploads reset circuit confirmation');
  await page.locator('#start-ms').fill('0');await page.locator('#end-ms').fill('0.8');
  await page.locator('#identify').click();await ready();
  const diagnostics=JSON.parse(await page.locator('#diagnostic-text').textContent());
  assert.equal(diagnostics.conditions.pwm_source,'measured');
  assert.equal(diagnostics.method.drive_source,'measured PWM');
  assert.equal(diagnostics.method.pwm_reconstruction,undefined);
  assert(!(await page.locator('#result-notes').textContent()).includes('PWM reconstruction completed'));
  await page.reload();await ready();
  assert.equal(await page.locator('#pwm-source').inputValue(),'auto');
  assert.notEqual(await page.locator('#result-l').textContent(),'—','Measured result survives restore in auto mode');
  assert.deepEqual(errors,[]);
  console.log('PASS: optional PWM auto routing, three-column reconstruction, actual PWM bypass, confirmation reset, fixed-R LC, history restore, bilingual copy and mobile layout.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
