const {chromium}=require('../.tmp/browser/node_modules/playwright-core');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
 const page=await browser.newPage({viewport:{width:1500,height:1050}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 let fits=0;page.on('request',r=>{if(r.url().endsWith('/api/identify'))fits++;});
 const ready=()=>page.locator('#load-demo:not([disabled])').waitFor({timeout:60000});
 try {
  await page.goto('http://127.0.0.1:8001');await ready();
  await page.locator('#load-demo').click();await ready();
  await page.locator('#enter-identification').click();
  await page.locator('#fit-method').selectOption('weighted_integral');
  await page.locator('#identify').click();
  await page.locator('#identify-complete-hint').waitFor();await ready();
  assert(await page.locator('#identify').isDisabled());
  assert.equal(await page.locator('#identify').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(220, 227, 226)');
  const result=await page.locator('.parameter-grid').innerText();
  await page.evaluate(()=>startFit());assert.equal(fits,1,'Completed configuration must not submit twice');
  await page.locator('#mapping-details').evaluate(el=>el.open=true);
  await page.locator('#apply-mapping').click();await ready();
  assert(await page.locator('#identify').isDisabled());
  assert.equal(await page.locator('.parameter-grid').innerText(),result);
  await page.locator('#language-toggle').click();
  assert.match(await page.locator('#identify-complete-hint').innerText(),/Change the parameters above/);
  await page.locator('#toggle-right-pane').click();await page.locator('#toggle-right-pane').click();
  await page.locator('#leave-identification').click();await page.locator('#enter-identification').click();
  assert(await page.locator('#identify').isDisabled());
  await page.reload();await ready();
  await page.locator('#enter-identification').click();
  await page.locator('#identify-complete-hint').waitFor();
  assert(await page.locator('#identify').isDisabled(),'Restored result locks the button');
  await page.locator('#vin').fill('29');
  assert(await page.locator('#identify').isEnabled());
  assert.match(await page.locator('#identify-complete-hint').innerText(),/Previous results remain/);
  assert(await page.locator('#download-report').isEnabled());
  await page.route('**/api/identify',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Test temporary failure'})}));
  await page.locator('#identify').click();await ready();
  assert(await page.locator('#identify').isEnabled(),'Failed submission must allow retry');
  await page.unroute('**/api/identify');
  await page.locator('#vin').fill('28');await page.locator('#identify').click();
  await page.locator('#identify-complete-hint').waitFor();await ready();
  assert(await page.locator('#identify').isDisabled());
  await page.locator('#train-fraction').fill('75');
  assert(await page.locator('#identify').isEnabled(),'Training split change unlocks');
  await page.locator('#load-demo').click();await ready();
  assert(await page.locator('#identify').isEnabled(),'New data unlocks');
  assert.deepEqual(errors,[]);
  console.log('PASS: success lock and grey style, duplicate guard, unchanged mapping, language/panel changes, reload restoration, parameter edits, retry after failure and new data.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
