// Run against the local backend on port 8001; no model API key is required.
const {chromium} = require('../.tmp/browser/node_modules/playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
(async () => {
  const browser = await chromium.launch({executablePath:process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
  const context = await browser.newContext({viewport:{width:1500,height:1050}});
  const page = await context.newPage(), errors = [];
  page.on('pageerror',error => errors.push(error.message));
  try {
    await fs.mkdir('runtime',{recursive:true});
    await page.goto('http://127.0.0.1:8001/');
    await page.getByText('后端已连接',{exact:true}).waitFor();
    await page.locator('#chat-input').fill('保留我的草稿');
    await page.locator('#language-toggle').click();
    assert.equal(await page.locator('html').getAttribute('lang'),'en');
    assert.equal(await page.locator('#conversation-panel').getAttribute('aria-label'),'AI Lab Assistant');
    assert.equal(await page.locator('#chat-input').inputValue(),'保留我的草稿');
    assert.equal(await page.locator('#connection-status').textContent(),'Backend connected');
    assert.equal(await page.locator('#language-toggle').getAttribute('aria-label'),'Switch to Chinese');
    assert((await page.locator('[data-prompt]').first().getAttribute('data-prompt')).startsWith('Analyze'));
    assert(!/[\u3400-\u9fff]/.test(await page.locator('#history-content').innerText()),'History and backup instructions must be English');
    assert(!/[\u3400-\u9fff]/.test(await page.locator('.chat-footnote').innerText()),'Backup and recovery copy must be English');
    await page.locator('#chat-input').fill('');
    await page.screenshot({path:'runtime/interface-english.png',fullPage:true});
    await page.reload();
    await page.getByText('Backend connected',{exact:true}).waitFor();
    assert.equal(await page.locator('html').getAttribute('lang'),'en','Language persists after reload');
    const storageState = await context.storageState();
    const fresh = await browser.newContext({storageState});
    const reopened = await fresh.newPage();
    await reopened.goto('http://127.0.0.1:8001/');
    assert.equal(await reopened.locator('html').getAttribute('lang'),'en','Language persists in a fresh session');
    await fresh.close();
    await page.locator('#open-settings').click();
    assert.equal(await page.locator('#settings-dialog h2').textContent(),'Connect your backend');
    assert.equal(await page.locator('#forget-access-token').textContent(),'Forget saved access code');
    assert.equal(await page.locator('#copy-sync-code').textContent(),'Copy sync recovery code');
    assert(!/[\u3400-\u9fff]/.test(await page.locator('#settings-dialog').innerText()),'Recovery-code help must be English');
    await page.locator('#close-settings').click();
    await page.locator('#load-demo').click();
    await page.locator('#file-info').waitFor();
    await page.waitForFunction(()=>!document.getElementById('load-demo').disabled);
    await page.locator('#enter-identification').click();
    assert.equal(await page.locator('#fit-mode').inputValue(),'LCR');
    const supportsPann=await page.locator('#fit-method option[value=pann]').evaluate(el=>!el.disabled);
    assert.equal(await page.locator('#fit-method').inputValue(),supportsPann?'pann':'weighted_integral');
    await page.locator('#fit-method').selectOption('weighted_integral');
    assert.equal(await page.locator('#job-status').textContent(),'Data ready · Identification available');
    const filename = await page.locator('#file-name').textContent();
    await page.locator('#identify').click();
    await page.locator('#job-status').filter({hasText:'Identification complete'}).waitFor({timeout:60000});
    assert.equal(await page.locator('#result-l').textContent(),'60');
    const capacitance = await page.locator('#result-c').textContent();
    assert(Math.abs(Number(capacitance)-500)<5,'Clean demo C stays within 1% of reference');
    assert((await page.locator('#result-notes').textContent()).includes('Parameter errors against ground truth have not been calculated'));
    assert(!/[\u3400-\u9fff]/.test(await page.locator('#diagnostic-text').textContent()),'Measured-PWM diagnostics must be English');
    const before = await page.locator('#current-chart path').first().getAttribute('d');
    await page.locator('#language-toggle').click();
    assert.equal(await page.locator('#job-status').textContent().then(s=>s.startsWith('辨识完成')),true);
    assert.equal(await page.locator('#result-l').textContent(),'60');
    assert.equal(await page.locator('#result-c').textContent(),capacitance,'Language switch preserves the computed value');
    assert.equal(await page.locator('#end-ms').inputValue(),'0.8');
    assert.equal(await page.locator('#file-name').textContent(),filename);
    assert.equal(await page.locator('#current-chart path').first().getAttribute('d'),before);
    await page.locator('#chat-input').fill('分析当前结果');
    await page.locator('#send-chat').click();
    await page.locator('.message.assistant').filter({hasText:'RMSE'}).waitFor();
    const answer = await page.locator('.message.assistant .message-content').textContent();
    await page.locator('#language-toggle').click();
    assert.equal(await page.locator('.message.assistant .message-content').textContent(),answer,'Existing conversation stays unchanged');
    await page.evaluate(()=>window.scrollTo(0,0));
    await page.screenshot({path:'runtime/interface-english-results.png',fullPage:true});
    for (const width of [390,320,900]) {
      await page.setViewportSize({width,height:900});
      assert(!(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth + 1)),`No overflow at ${width}px`);
      assert(await page.locator('#language-toggle').isVisible());
      if(width===390)await page.screenshot({path:'runtime/interface-english-mobile.png',fullPage:true});
    }
    await page.setViewportSize({width:1500,height:1050});
    await page.locator('#vin').fill('30');
    assert.equal(await page.locator('#result-l').textContent(),'—');
    await page.locator('#language-toggle').click();
    assert.equal(await page.locator('#result-l').textContent(),'—','Switching language must not restore invalidated results');
    assert.equal(await page.locator('#vin').inputValue(),'30');
    await page.locator('#leave-identification').click();
    await page.locator('#clear-data').click();
    await page.locator('#file-info').waitFor({state:'hidden'});
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({passed:true,persistence:true,englishIdentification:true,dataPreserved:true,conversationPreserved:true,mobile:true,errors},null,2));
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
