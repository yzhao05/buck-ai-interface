// Local QA: npm install --prefix .tmp/browser playwright-core
const {chromium} = require('../.tmp/browser/node_modules/playwright-core');
const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
(async () => {
  fs.mkdirSync('runtime', {recursive:true});
  const browser = await chromium.launch({executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless:true});
  const context = await browser.newContext({viewport:{width:1500,height:1050},deviceScaleFactor:1});
  await context.addInitScript(() => localStorage.setItem('buck-api-url','http://127.0.0.1:8001'));
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:5500', {waitUntil:'networkidle'});
  await page.getByText('后端已连接', {exact:true}).waitFor();
  assert(await page.locator('#analysis-panel').isHidden());
  assert(await page.locator('#identification-form').isHidden());
  assert(await page.locator('#enter-identification').isVisible());
  const defaultChat = await page.locator('#conversation-panel').boundingBox();
  assert(defaultChat.width > 1000, 'Default chat should occupy the main workspace');
  for (const [button, content] of [['toggle-import','import-content']]) {
    await page.locator('#'+button).click();
    assert(await page.locator('#'+content).isHidden());
    await page.locator('#'+button).click();
    assert(await page.locator('#'+content).isVisible());
  }
  await page.screenshot({path:'runtime/interface-empty.png',fullPage:true});
  await page.locator('#load-demo').click();
  await page.locator('#file-info').waitFor();
  await page.waitForFunction(() => !document.getElementById('load-demo').disabled);
  assert(await page.locator('#analysis-panel').isHidden(), 'Import must not open identification');
  await page.locator('#chat-input').fill('开始参数辨识');
  await page.locator('#send-chat').click();
  await page.locator('.message.assistant').filter({hasText:'进入参数辨识'}).waitFor();
  assert(await page.locator('#analysis-panel').isHidden());
  // Keep this conversation's CSV for the identification flow. New chat intentionally isolates data.
  await page.locator('#enter-identification').click();
  assert(await page.locator('#identification-form').isVisible());
  assert(await page.locator('#analysis-panel').isVisible());
  const chatBox = await page.locator('#conversation-panel').boundingBox();
  const analysisBox = await page.locator('#analysis-panel').boundingBox();
  assert(chatBox.x < analysisBox.x && chatBox.width > analysisBox.width, 'Chat stays central and analysis opens on its right');
  await page.locator('#job-status').filter({hasText:'可开始辨识'}).waitFor();
  await page.locator('#identify').click();
  await page.locator('#job-status').filter({hasText:'辨识完成'}).waitFor({timeout:60000});
  const values = await page.locator('.parameter-grid').innerText();
  if (!(values.includes('60') && values.includes('500'))) throw new Error('Unexpected parameters: '+values);
  await page.locator('#close-analysis').click();
  assert(await page.locator('#analysis-panel').isHidden());
  assert(await page.locator('#identification-form').isHidden());
  assert(await page.locator('#enter-identification').isVisible());
  assert(await page.locator('#file-info').isVisible());
  await page.locator('#enter-identification').click();
  assert.equal(await page.locator('.parameter-grid').innerText(), values, 'Results survive exiting identification');
  assert.equal(await page.locator('#end-ms').inputValue(), '0.8');
  await page.locator('#ask-error').click();
  await page.locator('.message.assistant').filter({hasText:'RMSE'}).waitFor({timeout:30000});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.waitForTimeout(200);
  await page.screenshot({path:'runtime/interface-desktop.png',fullPage:true});
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#download-report').click();
  const download = await downloadPromise;
  await download.saveAs('runtime/browser-export.json');
  const report = JSON.parse(fs.readFileSync('runtime/browser-export.json','utf8'));
  if (!report.result?.file_sha256) throw new Error('Missing provenance in report');
  await page.locator('#view-tail').click();
  await page.locator('#view-full').click();
  await page.locator('#chat-input').fill('这个电容还有多少年寿命？');
  await page.locator('#send-chat').click();
  await page.locator('.message.assistant').filter({hasText:'不能从这份短时波形'}).waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.waitForTimeout(200);
  await page.screenshot({path:'runtime/interface-mobile.png',fullPage:true});
  const overflow = await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);
  if (overflow) throw new Error('Mobile page overflows horizontally');
  await page.setViewportSize({width:900,height:1000});
  assert(!(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1)), 'Tablet must not overflow');
  await page.setViewportSize({width:1500,height:1050});
  await page.locator('#csv-file').setInputFiles(path.resolve('examples/plecs_buck_case16a.csv'));
  await page.locator('#job-status').filter({hasText:'可开始辨识'}).waitFor();
  await page.locator('#map-pwm').selectOption('');
  await page.locator('#apply-mapping').click();
  await page.locator('#job-status').filter({hasText:'还需要 PWM'}).waitFor();
  await page.locator('#identify').click();
  await page.locator('#notice').filter({hasText:'参数辨识需要 PWM'}).waitFor();
  await page.locator('#map-pwm').selectOption('Relational Operator');
  await page.locator('#apply-mapping').click();
  await page.locator('#job-status').filter({hasText:'可开始辨识'}).waitFor();
  const pannEnabled = !(await page.locator('#fit-method option[value="pann"]').isDisabled());
  const testPann = pannEnabled && process.env.RUN_PANN === '1';
  if (testPann) {
    await page.locator('#start-ms').fill('0');
    await page.locator('#end-ms').fill('0.8');
    await page.locator('#fit-method').selectOption('pann');
    await page.locator('#identify').click();
    await page.locator('#job-status').filter({hasText:'辨识完成'}).waitFor({timeout:180000});
    if (!(await page.locator('#diagnostic-text').textContent()).includes('PANN')) throw new Error('PANN result missing');
  }
  if (errors.length) throw new Error(errors.join('\n'));
  console.log(JSON.stringify({passed:true,values,chatPrimary:true,explicitEntry:true,collapseExpand:true,preservedResults:true,crossOrigin:true,report:true,mobile:true,tablet:true,missingPwm:true,pann:testPann,browserErrors:errors},null,2));
  await browser.close();
})().catch(error => {console.error(error);process.exit(1);});
